#!/usr/bin/env node
// Extracts built-in function/procedure names and signatures from the
// CommuniGate Pro developer documentation, so the TextMate grammars and the
// language server never hand-maintain a separate copy of the function list.
//
// Input is the pages published at https://doc.communigatepro.ru/development/,
// either as fetched HTML (tools/fetch-docs.mjs) or as a local Markdown copy.
// CGPRO_DOCS_ROOT points at the directory holding them.
//
// Two shapes are used across those documents:
//   the CG/PL page          #### `Name(args)` {#Anchor}
//   PBXApp/WebApp/WSSP      - `Name(args)`     (top-level bullet, column 0)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const docsRoot = process.env.CGPRO_DOCS_ROOT ?? path.resolve(here, '../docs');

// name may be a plain identifier, or WSSP's `<!--%%IF expression-->` style,
// or a comma-free signature list on separate lines (ProcCall style).
const NAME_RE = String.raw`(?:<!--%%)?[A-Za-z_][A-Za-z0-9_]*`;

// --- HTML input -------------------------------------------------------------
// The pages published at doc.communigatepro.ru are the public form of the same
// documentation, and they carry the same two shapes:
//   <h4 id="Substring"><code>Substring(str,from,len)</code>...</h4><p>prose
//   <li><p><code>AcceptCall()</code></p><p>prose
// Supporting them means the built-in database can be regenerated by anyone
// with a network connection, rather than only from a local Markdown copy.

const ENTITIES = {
  amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', shy: '',
  mdash: '—', ndash: '–', hellip: '…', laquo: '«', raquo: '»',
};

function decodeEntities(s) {
  return s
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(Number(dec)))
    .replace(/&([a-zA-Z]+);/g, (m, name) => (name in ENTITIES ? ENTITIES[name] : m));
}

/** An HTML fragment reduced to the plain prose `summarize` expects. */
function htmlToText(fragment) {
  return decodeEntities(
    fragment
      .replace(/<pre[\s\S]*?<\/pre>/gi, ' ') // code samples are not prose
      .replace(/<table[\s\S]*?<\/table>/gi, ' ') // nor are key/value tables
      .replace(/<br\s*\/?>/gi, ' ')
      .replace(/<\/(p|div|li|h[1-6])>/gi, '\n')
      .replace(/<[^>]+>/g, ''),
  )
    .replace(/[ \t]{2,}/g, ' ')
    .trim();
}

function extractFromHtml(html) {
  const entries = [];

  // Heading form. The id attribute is the documentation anchor.
  const headings = [...html.matchAll(/<h([2-6])\s+id="([^"]*)"[^>]*>\s*<code>([^<]*)<\/code>[\s\S]*?<\/h\1>/g)];
  for (let i = 0; i < headings.length; i++) {
    const m = headings[i];
    const sig = decodeEntities(m[3]).trim();
    const nameMatch = sig.match(new RegExp(`^(${NAME_RE})`));
    if (!nameMatch) continue;
    const bodyStart = m.index + m[0].length;
    // The description runs to the next heading of any level.
    const rest = html.slice(bodyStart);
    const nextHeading = rest.search(/<h[2-6][\s>]/);
    let body = nextHeading < 0 ? rest : rest.slice(0, nextHeading);

    // Overloads are written as paragraphs of bare code spans directly after
    // the heading, e.g. DeactivateMeeting(setName,key) in the heading with
    // DeactivateMeeting(setName,key,parameter) in the paragraph below. Pull
    // those out as further signatures - otherwise they are neither offered in
    // signature help nor removed from the prose, and every hover for such a
    // function opens with a stray signature.
    const overloads = [];
    const LEADING_CODE_PARA = /^\s*<p>\s*((?:<code>[^<]*<\/code>\s*(?:<br\s*\/?>\s*)?)+)<\/p>/;
    for (;;) {
      const lead = LEADING_CODE_PARA.exec(body);
      if (!lead) break;
      const spans = [...lead[1].matchAll(/<code>([^<]*)<\/code>/g)].map((c) => decodeEntities(c[1]).trim());
      // Only consume the paragraph if every span really is a signature for
      // this same function; otherwise it is ordinary prose that happens to
      // start with code.
      if (!spans.length || !spans.every((s) => s.toLowerCase().startsWith(`${nameMatch[1].toLowerCase()}(`))) {
        break;
      }
      overloads.push(...spans);
      body = body.slice(lead[0].length);
    }

    const doc = summarize(htmlToText(body));
    for (const signature of [sig, ...overloads]) {
      entries.push({
        name: nameMatch[1],
        signature,
        anchor: m[2] || null,
        params: paramsOf(signature),
        doc,
      });
    }
  }

  // Bullet form: a list item whose first paragraph holds nothing but code
  // spans. Overloads are written as several spans separated by <br> inside
  // that one paragraph - PlayFile(fileName) / PlayFile(fileName,msec) - so
  // every span is captured, not just the first.
  const BULLET = /<li>\s*<p>\s*((?:<code>[^<]*<\/code>\s*(?:<br\s*\/?>\s*)?)+)<\/p>([\s\S]*?)<\/li>/g;
  for (const m of html.matchAll(BULLET)) {
    const signatures = [...m[1].matchAll(/<code>([^<]*)<\/code>/g)].map((c) => decodeEntities(c[1]).trim());
    const doc = summarize(htmlToText(m[2]));
    for (const sig of signatures) {
      if (sig.startsWith('<!--%%')) continue; // WSSP structural tag
      const callMatch = sig.match(new RegExp(`^(${NAME_RE})\\(`));
      if (!callMatch) continue; // a bare dataset key, not a callable
      entries.push({
        name: callMatch[1],
        signature: sig,
        anchor: null,
        params: paramsOf(sig),
        doc,
      });
    }
  }

  return entries;
}

function extractWsspStructuralTagsFromHtml(html) {
  const out = [];
  for (const m of html.matchAll(/<code>&lt;!--%%([A-Z]+)/g)) {
    out.push({ name: m[1], signature: `<!--%%${m[1]}-->`, anchor: null });
  }
  return out;
}

// Turns the markdown prose that documents one builtin into a short plain-text
// summary suitable for an LSP hover popup. Keeps it to the first few
// sentences: hovers are read at a glance, and the full text is a click away
// in the docs.
function summarize(body) {
  const text = body
    .replace(/```[\s\S]*?```/g, '') // drop fenced examples
    .replace(/^\s*[|:-]{2,}.*$/gm, '') // drop table rules
    .replace(/\r/g, '')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'))
    .join(' ')
    .replace(/\s{2,}/g, ' ')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1') // links -> their text
    .replace(/_([^_]+)_/g, '$1')
    .trim();
  if (!text) return '';
  const sentences = text.match(/[^.]+\.(?:\s|$)/g);
  if (!sentences) return text.slice(0, 400);
  let out = '';
  for (const s of sentences) {
    if (out.length + s.length > 400) break;
    out += s;
  }
  return (out || sentences[0]).trim();
}

/** Splits `Name(a, b)` into its parameter names, or [] when there are none. */
function paramsOf(signature) {
  const open = signature.indexOf('(');
  if (open < 0) return [];
  const close = signature.lastIndexOf(')');
  const inner = signature.slice(open + 1, close < 0 ? undefined : close).trim();
  if (!inner) return [];
  return inner.split(',').map((p) => p.trim()).filter(Boolean);
}

// Collects every match of `re` plus the text between it and the next match
// (or end of document). Done by slicing on match offsets rather than with a
// terminating lookahead: JavaScript has no \Z, and using it silently drops
// the last entry in the file, which is exactly the kind of quiet gap this
// whole generate-from-docs approach exists to avoid.
function matchesWithBodies(text, re) {
  const found = [];
  let m;
  while ((m = re.exec(text))) {
    found.push({ groups: m, headEnd: m.index + m[0].length });
  }
  return found.map((entry, i) => ({
    groups: entry.groups,
    body: text.slice(entry.headEnd, i + 1 < found.length ? found[i + 1].groups.index : text.length),
  }));
}

function extractHeadingStyle(text) {
  // #### `Name(args)` {#Anchor}   followed by the prose describing it
  const re = /^#{2,5}[ \t]+`([^`]+)`(?:[ \t]*\{#([^}]+)\})?[^\n]*/gm;
  const out = [];
  for (const { groups, body } of matchesWithBodies(text, re)) {
    const sig = groups[1].trim();
    const nameMatch = sig.match(new RegExp(`^(${NAME_RE})`));
    if (!nameMatch) continue;
    out.push({
      name: nameMatch[1],
      signature: sig,
      anchor: groups[2] ?? null,
      params: paramsOf(sig),
      doc: summarize(body),
    });
  }
  return out;
}

function extractBulletStyle(text) {
  // Top-level (column 0) bullet: - `Name(args)`
  // PBXApp/WebApp/WSSP.md use this SAME bullet convention for two unrelated
  // things: actual function/procedure calls (`AcceptCall()`) and bare
  // dataset-key names documented inline (`charset`, `attendees`). Only the
  // former are callable identifiers a grammar should highlight as
  // support.function - keep bullets whose signature is an actual call,
  // i.e. `Name(`.
  // The indented prose under the bullet is the description.
  const re = /^- `([^`]+)`[ \t]*$/gm;
  const functions = [];
  for (const { groups, body } of matchesWithBodies(text, re)) {
    const sig = groups[1].trim();
    if (sig.startsWith('<!--%%')) continue; // WSSP structural tag, handled separately
    const callMatch = sig.match(new RegExp(`^(${NAME_RE})\\(`));
    if (!callMatch) continue; // bare dataset-key bullet, not a callable
    functions.push({
      name: callMatch[1],
      signature: sig,
      anchor: null,
      params: paramsOf(sig),
      // A bullet's body runs to the next bullet, which may be in a different
      // section; cut at the next heading so a description can't bleed across.
      doc: summarize(body.split(/^#{1,5}[ \t]/m)[0]),
    });
  }
  return functions;
}

function extractWsspStructuralTags(text) {
  // WSSP structural elements (`<!--%%IF expr-->` ... `<!--%%ENDIF-->`) are
  // documented inline, not always as their own bullet (e.g. ELIF/ENDIF are
  // just mentioned in prose) - so scan the whole doc for the tag spelling
  // rather than relying on bullet position.
  const re = /`<!--%%([A-Z]+)/g;
  const out = [];
  let m;
  while ((m = re.exec(text))) out.push({ name: m[1], signature: `<!--%%${m[1]}-->`, anchor: null });
  return out;
}

function dedupe(entries) {
  const byName = new Map();
  for (const e of entries) {
    if (!byName.has(e.name)) {
      byName.set(e.name, {
        name: e.name,
        signatures: [],
        params: e.params ?? [],
        doc: e.doc ?? '',
        anchor: e.anchor ?? null,
      });
    }
    const bucket = byName.get(e.name);
    if (!bucket.signatures.includes(e.signature)) bucket.signatures.push(e.signature);
    // Overloads are documented as several headings; keep the longest
    // parameter list and the first non-empty description.
    if ((e.params?.length ?? 0) > bucket.params.length) bucket.params = e.params;
    if (!bucket.doc && e.doc) bucket.doc = e.doc;
  }
  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * Loads one documentation page. Either form works: the HTML published at
 * doc.communigatepro.ru (fetch it with tools/fetch-docs.mjs) or a local
 * Markdown copy. Returns the text along with which form it is, since the two
 * need different extraction.
 */
function loadDoc(page) {
  for (const ext of ['.html', '.md']) {
    const full = path.join(docsRoot, page + ext);
    if (existsSync(full)) return { text: readFileSync(full, 'utf8'), html: ext === '.html' };
  }
  console.error(
    `Cannot find ${page}.html or ${page}.md under ${docsRoot}.\n` +
      'Run "node tools/fetch-docs.mjs" to download the published documentation,\n' +
      'or set CGPRO_DOCS_ROOT to a directory that already holds it.',
  );
  process.exit(1);
}

/** Functions documented as headings (the CG/PL page). */
function headingStyle(page) {
  const { text, html } = loadDoc(page);
  return html ? extractFromHtml(text) : extractHeadingStyle(text);
}

/** Functions documented as bullets (the PBXApp, WebApp and WSSP pages). */
function bulletStyle(page) {
  const { text, html } = loadDoc(page);
  // The HTML extractor handles both shapes, so one call covers either form.
  return html ? extractFromHtml(text) : extractBulletStyle(text);
}

const wssp = loadDoc('WSSP');

const categories = {
  cgpl: dedupe(headingStyle('CGPL')),
  pbxapp: dedupe(bulletStyle('PBXApp')),
  webapp: dedupe(bulletStyle('WebApp')),
  wssp: dedupe(wssp.html ? extractFromHtml(wssp.text) : extractBulletStyle(wssp.text)),
  wsspStructural: dedupe(
    wssp.html ? extractWsspStructuralTagsFromHtml(wssp.text) : extractWsspStructuralTags(wssp.text),
  ),
};

// Sanity: fail loudly instead of silently shipping an empty/half grammar.
const MIN_EXPECTED = { cgpl: 150, pbxapp: 20, webapp: 5, wssp: 30, wsspStructural: 8 };
for (const [cat, min] of Object.entries(MIN_EXPECTED)) {
  if (categories[cat].length < min) {
    throw new Error(
      `extract-builtins: ${cat} yielded only ${categories[cat].length} entries ` +
        `(expected >= ${min}) - doc heading pattern probably changed, check ${cat} source doc`,
    );
  }
}

// Merge in tools/builtins-registry.json - the full roster of built-ins the
// server provides, each with its argument counts and whether it is a
// function or a procedure. It covers every built-in, not just the obscure
// ones: the documentation states no argument counts anywhere, so the roster
// supplies those even for thoroughly documented functions. It also carries
// the ones no document mentions (TextToObject, StartPBXTask and friends),
// which would otherwise be reported as unknown calls in perfectly good code.
// The two inputs are complementary: the roster supplies existence and arity,
// the documentation supplies the descriptions.
const registryFile = path.resolve(here, 'builtins-registry.json');
let merged = { fromDocsOnly: 0, fromRegistryOnly: 0, both: 0 };
if (existsSync(registryFile)) {
  const registry = JSON.parse(readFileSync(registryFile, 'utf8'));
  for (const [env, entries] of Object.entries(registry)) {
    // Environments outside the three the grammars know about fold into the
    // core list rather than being dropped.
    const target = ['cgpl', 'pbxapp', 'webapp'].includes(env) ? env : 'cgpl';
    const bucket = categories[target] ?? (categories[target] = []);
    const byLower = new Map(bucket.map((e) => [e.name.toLowerCase(), e]));
    for (const e of entries) {
      const existing = byLower.get(e.name.toLowerCase());
      if (existing) {
        existing.minArgs = e.minArgs;
        existing.maxArgs = e.maxArgs;
        existing.isFunction = e.isFunction;
        existing.source = 'both';
        merged.both++;
      } else {
        bucket.push({
          name: e.name,
          signatures: [`${e.name}(${e.minArgs === 0 && e.maxArgs === 0 ? '' : '...'})`],
          params: [],
          doc: '',
          anchor: null,
          minArgs: e.minArgs,
          maxArgs: e.maxArgs,
          isFunction: e.isFunction,
          aliasOf: e.aliasOf ?? null,
          source: 'registry',
        });
        merged.fromRegistryOnly++;
      }
    }
    bucket.sort((a, b) => a.name.localeCompare(b.name));
  }
  for (const bucket of Object.values(categories)) {
    for (const e of bucket) {
      if (!e.source) {
        e.source = 'docs';
        merged.fromDocsOnly++;
      }
    }
  }
  // Some built-ins are two names for one implementation - the whole
  // ReadSiteFile / ReadStorageFile family, for instance. Only one name of
  // each pair is documented, but an alias behaves identically, so it can
  // borrow its twin's description instead of showing nothing. The pairing is
  // recorded by hand in the registry's `aliasOf` field; the arity of both
  // names matches, which is what makes the claim checkable.
  let aliases = 0;
  const documented = new Map();
  for (const bucket of Object.values(categories)) {
    for (const e of bucket) if (e.source !== 'registry') documented.set(e.name.toLowerCase(), e);
  }
  for (const bucket of Object.values(categories)) {
    for (const e of bucket) {
      if (!e.aliasOf) continue;
      const target = documented.get(e.aliasOf.toLowerCase());
      if (!target) continue;
      // Present the alias under its own name, with the documented twin's
      // parameters and prose.
      e.signatures = target.signatures.map((s) => s.replace(/^[A-Za-z_][A-Za-z0-9_]*/, e.name));
      e.params = target.params;
      e.doc = target.doc;
      e.anchor = target.anchor;
      e.source = 'alias';
      aliases++;
    }
  }

  console.log(
    `merged with the registry: ${merged.both} documented and registered, ` +
      `${merged.fromRegistryOnly} registered but undocumented ` +
      `(${aliases} of them synonyms of a documented function), ` +
      `${merged.fromDocsOnly} documented only`,
  );
} else {
  console.log('note: tools/builtins-registry.json not found - built-ins are docs-derived only');
}

const outFile = path.resolve(here, 'builtins.json');
writeFileSync(outFile, JSON.stringify(categories, null, 2) + '\n');

for (const [cat, entries] of Object.entries(categories)) {
  console.log(`${cat}: ${entries.length} builtins`);
}
console.log(`wrote ${outFile}`);
